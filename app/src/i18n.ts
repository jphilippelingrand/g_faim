export const LANGS = ["fr", "en", "es"] as const;
export type Lang = (typeof LANGS)[number];

export const lang: Lang =
  getLocales()
    .map((l) => l.languageCode)
    .find((c): c is Lang => LANGS.includes(c as Lang)) ?? "fr";

